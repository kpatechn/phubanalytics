-- The player base: every account in WinStar's patron master. Because a central system
-- syncs profiles, this sample stands in for the enterprise list. Only the account number,
-- state, tier, sign-up date and exclusion flag are used: no names or contacts.
-- Tier is the real one when the club-level sample has it, otherwise drawn 75/18/7.
CREATE TABLE cdp_mock.player AS
WITH club AS (
    SELECT DISTINCT ON (account_number) account_number, card_level::integer AS card_level
    FROM dexiga.customer_club_level
    WHERE card_level IN (92, 93, 94)
    ORDER BY account_number, date_modified DESC NULLS LAST
),
base AS (
    SELECT trim(m.account_number)::numeric AS account_number,
           CASE upper(trim(m.residential_state)) WHEN 'TX' THEN 'TX' WHEN 'OK' THEN 'OK' ELSE 'OTHER' END AS home_region,
           CASE WHEN m.date_created ~ '^\d{4}-\d\d-\d\d$' THEN m.date_created::date END AS signup_date,
           c.card_level AS real_card_level
    FROM dexiga.customer_master m
    LEFT JOIN club c ON c.account_number = trim(m.account_number)::numeric
    WHERE trim(m.account_number) ~ '^\d+$'
)
SELECT b.account_number,
       'Y'::text AS corporate_id,
       coalesce(b.real_card_level,
                cdp_mock.wpick('tier:' || b.account_number, '{94,93,92}', '{75,18,7}')::integer) AS card_level,
       CASE WHEN b.real_card_level IS NOT NULL THEN 'real' ELSE 'mock' END AS tier_source,
       b.home_region,
       coalesce(b.signup_date, (SELECT start_date FROM cdp_mock.params) - (cdp_mock.u('signup:' || b.account_number) * 3650)::integer) AS signup_date,
       -- Lognormal spend index, mean about 1: most players modest, a few whales.
       exp(0.9 * cdp_mock.n('value:' || b.account_number) - 0.405) AS value_index,
       EXISTS (SELECT 1 FROM dexiga.exclusion_history e WHERE e.account_number = b.account_number) AS is_excluded
FROM base b;

