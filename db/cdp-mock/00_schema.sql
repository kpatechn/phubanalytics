-- Uniform [0, 1) from a key.
CREATE FUNCTION cdp_mock.u(key text) RETURNS double precision
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    RETURN (hashtextextended(key, 20261023) & 9007199254740991)::double precision / 9007199254740992;

-- Standard normal from a key (Box-Muller).
CREATE FUNCTION cdp_mock.n(key text) RETURNS double precision
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    RETURN sqrt(-2 * ln(1 - cdp_mock.u(key || '#a'))) * cos(2 * pi() * cdp_mock.u(key || '#b'));

-- Exponential with the given mean: many small values, a long tail (visit counts, spend).
CREATE FUNCTION cdp_mock.expo(key text, mean double precision) RETURNS double precision
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    RETURN -ln(1 - cdp_mock.u(key)) * mean;

-- One value from a weighted list.
CREATE FUNCTION cdp_mock.wpick(key text, vals text[], weights double precision[]) RETURNS text
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    RETURN (
        SELECT v FROM (
            SELECT v, sum(w) OVER (ORDER BY i) AS upto, sum(w) OVER () AS total
            FROM unnest(vals, weights) WITH ORDINALITY AS x(v, w, i)
        ) s
        WHERE upto > cdp_mock.u(key) * total
        ORDER BY upto LIMIT 1
    );

-- One value from a list, all equally likely.
CREATE FUNCTION cdp_mock.pick(key text, vals text[]) RETURNS text
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    RETURN vals[1 + floor(cdp_mock.u(key) * cardinality(vals))::integer];

-- A time of day from a key, between from_hour and from_hour + span_hours (wraps past midnight).
CREATE FUNCTION cdp_mock.clock(key text, from_hour integer, span_hours integer) RETURNS time
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    RETURN time '00:00' + make_interval(hours => from_hour, mins => floor(cdp_mock.u(key) * span_hours * 60)::integer);

-- A stable UUID from a key.
CREATE FUNCTION cdp_mock.uuid(key text) RETURNS uuid
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    RETURN md5('cdp_mock:' || key)::uuid;

-- A player's mock email and mobile number, or NULL when the player has none on file
-- (78% and 72% do). Reserved, non-routable values only: example.com, and the unassigned
-- +1 555 area code. Defined here because hotel stays and contact points must agree.
CREATE FUNCTION cdp_mock.player_email(account_number numeric) RETURNS text
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    RETURN CASE WHEN cdp_mock.u('hasemail:' || account_number) < 0.78 THEN 'cp' || account_number || '@example.com' END;

CREATE FUNCTION cdp_mock.player_mobile(account_number numeric) RETURNS text
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    RETURN CASE WHEN cdp_mock.u('hasmobile:' || account_number) < 0.72 THEN '+1555' || lpad((account_number % 10000000)::text, 7, '0') END;

-- Local date and time at a site (all Chickasaw sites are on Central time) as timestamptz.
CREATE FUNCTION cdp_mock.at_site(d date, t time) RETURNS timestamptz
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    RETURN (d + t) AT TIME ZONE 'America/Chicago';

-- Loyalty day number used by the WinStar files (days since 1899-12-30).
CREATE FUNCTION cdp_mock.day_number(d date) RETURNS integer
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    RETURN d - date '1899-12-30';

