#!/usr/bin/env bash
# Writes apps/api/.env for local development from your libpq service entries
# (~/.pg_service.conf) and password file (~/.pgpass). Prints no secrets.
# Usage: scripts/write-dev-env.sh [service] [gem-service]   (defaults: graton-dev, gem-dev)
# The GEM entry (Chickasaw CDP, database dexiga) is optional: without it the CDP stays off.
set -euo pipefail

SERVICE="${1:-graton-dev}"
GEM_SERVICE="${2:-gem-dev}"
OUT="$(cd "$(dirname "$0")/.." && pwd)/apps/api/.env"

python3 -I - "$SERVICE" "$GEM_SERVICE" "$OUT" <<'PY'
import configparser, os, sys, urllib.parse

service, gem_service, out = sys.argv[1], sys.argv[2], sys.argv[3]
conf = configparser.ConfigParser()
conf.read(os.path.expanduser("~/.pg_service.conf"))

def fields(line):
    out, cur, esc = [], "", False
    for ch in line:
        if esc: cur += ch; esc = False
        elif ch == "\\": esc = True
        elif ch == ":": out.append(cur); cur = ""
        else: cur += ch
    out.append(cur)
    return out

def url_for(name, database):
    s = conf[name]
    host, port, user = s["host"], s.get("port", "5432"), s["user"]
    password = None
    with open(os.path.expanduser("~/.pgpass")) as f:
        for raw in f:
            line = raw.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            parts = fields(line)
            if len(parts) != 5:
                continue
            h, p, d, u, pw = parts
            if h in ("*", host) and p in ("*", port) and d in ("*", database) and u in ("*", user):
                password = pw
                break
    if password is None:
        sys.exit(f"no ~/.pgpass entry for {user}@{host}:{port}")
    q = urllib.parse.quote
    return f"postgres://{q(user, safe='')}:{q(password, safe='')}@{host}:{port}/{database}", f"{user}@{host}/{database}"

if service not in conf:
    sys.exit(f"service [{service}] not found in ~/.pg_service.conf")
url, label = url_for(service, "dexl")
lines = [
    "# Generated by scripts/write-dev-env.sh. Do not commit.",
    f"DATABASE_URL={url}",
    "DATABASE_SSL=require",
]
labels = [label]
if gem_service in conf:
    gem_url, gem_label = url_for(gem_service, "dexiga")
    # GEM dev offers no TLS; it is reachable only over the VPN.
    lines += [f"GEM_DATABASE_URL={gem_url}", "GEM_DATABASE_SSL=disable"]
    labels.append(gem_label)
lines += ["APP_ENVIRONMENT=dev", "AUTH_MODE=dev", "PORT=3000", "HOST=127.0.0.1", "LOG_LEVEL=info"]

fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
with os.fdopen(fd, "w") as f:
    f.write("\n".join(lines) + "\n")
os.chmod(out, 0o600)
print(f"wrote {out} for {' and '.join(labels)} (mode 600)")
PY
