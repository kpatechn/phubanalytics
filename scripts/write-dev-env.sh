#!/usr/bin/env bash
# Writes apps/api/.env for local development from your libpq service entry
# (~/.pg_service.conf) and password file (~/.pgpass). Prints no secrets.
# Usage: scripts/write-dev-env.sh [service]      (default: graton-dev)
set -euo pipefail

SERVICE="${1:-graton-dev}"
OUT="$(cd "$(dirname "$0")/.." && pwd)/apps/api/.env"

python3 -I - "$SERVICE" "$OUT" <<'PY'
import configparser, os, sys, urllib.parse

service, out = sys.argv[1], sys.argv[2]
conf = configparser.ConfigParser()
conf.read(os.path.expanduser("~/.pg_service.conf"))
if service not in conf:
    sys.exit(f"service [{service}] not found in ~/.pg_service.conf")
s = conf[service]
host, port, user = s["host"], s.get("port", "5432"), s["user"]
database = "dexl"

def fields(line):
    out, cur, esc = [], "", False
    for ch in line:
        if esc: cur += ch; esc = False
        elif ch == "\\": esc = True
        elif ch == ":": out.append(cur); cur = ""
        else: cur += ch
    out.append(cur)
    return out

password = None
with open(os.path.expanduser("~/.pgpass")) as f:
    for raw in f:
        line = raw.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        parts = fields(line)
        if len(parts) != 5:
            continue
        h, p, d, u, pw = parts
        if h in ("*", host) and p in ("*", port) and d in ("*", database) and u in ("*", user):
            password = pw
            break
if password is None:
    sys.exit(f"no ~/.pgpass entry for {user}@{host}:{port}")

q = urllib.parse.quote
url = f"postgres://{q(user, safe='')}:{q(password, safe='')}@{host}:{port}/{database}"
fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
with os.fdopen(fd, "w") as f:
    f.write(
        "# Generated by scripts/write-dev-env.sh. Do not commit.\n"
        f"DATABASE_URL={url}\n"
        "DATABASE_SSL=require\n"
        "APP_ENVIRONMENT=dev\n"
        "AUTH_MODE=dev\n"
        "PORT=3000\n"
        "HOST=127.0.0.1\n"
        "LOG_LEVEL=info\n"
    )
os.chmod(out, 0o600)
print(f"wrote {out} for {user}@{host}/{database} (mode 600)")
PY
